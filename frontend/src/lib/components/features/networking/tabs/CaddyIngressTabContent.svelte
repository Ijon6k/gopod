<script lang="ts">
	import type { Server } from '$lib/types';
	import { LayerCard, Badge, Button, useKumoToastManager } from 'kumo-svelte';
	import { CodeEditor } from '$lib/components/ui';
	import { CheckCircle, Lock, Check, Copy, ArrowsClockwise } from 'phosphor-svelte';
	import { api } from '$lib/api';

	interface Props {
		server: Server;
		caddyStatus: string;
		caddyAdminUrl: string;
		caddyHttpPort: number;
		caddyHttpsPort: number;
		caddyfileContent: string;
		isLoadingCaddyfile: boolean;
		isReloadingCaddy: boolean;
		onReloadCaddy: () => Promise<void>;
		onRetryLoadCaddyfile: () => void;
	}

	let {
		server,
		caddyStatus,
		caddyAdminUrl,
		caddyHttpPort,
		caddyHttpsPort,
		caddyfileContent,
		isLoadingCaddyfile,
		isReloadingCaddy,
		onReloadCaddy,
		onRetryLoadCaddyfile
	}: Props = $props();

	let copiedCaddyfile = $state(false);

	async function handleCopyCaddyfile() {
		try {
			await navigator.clipboard.writeText(caddyfileContent);
			copiedCaddyfile = true;
			setTimeout(() => (copiedCaddyfile = false), 2000);
		} catch {
			// fallback
		}
	}
</script>

<div class="flex flex-col gap-4">
	<!-- Caddy Ingress Architecture & Control -->
	<div class="grid grid-cols-1 gap-4 sm:grid-cols-3">
		<!-- Ingress Status -->
		<LayerCard class="flex flex-col gap-2 p-4">
			<div class="flex items-center justify-between">
				<span class="text-xs font-medium text-[var(--text-secondary)]">Ingress Daemon</span>
				<Badge variant={caddyStatus === 'error' ? 'error' : 'success'} class="gap-1.5 text-xs">
					<CheckCircle size={12} />
					{caddyStatus === 'error' ? 'Degraded' : 'Active (Rootless)'}
				</Badge>
			</div>
			<div class="mt-1 flex items-baseline gap-2">
				<span class="text-lg font-semibold text-[var(--text-primary)]"> Caddy</span>
				<span class="font-mono text-xs text-[var(--text-tertiary)]">rootless socket</span>
			</div>
			<span class="text-xs text-[var(--text-tertiary)]">
				Bound to host ports <span class="font-mono text-[11px] text-[var(--text-secondary)]"
					>:{caddyHttpPort}</span
				>
				(HTTP) &
				<span class="font-mono text-[11px] text-[var(--text-secondary)]">:{caddyHttpsPort}</span> (HTTPS)
			</span>
		</LayerCard>

		<!-- Admin API -->
		<LayerCard class="flex flex-col gap-2 p-4">
			<div class="flex items-center justify-between">
				<span class="text-xs font-medium text-[var(--text-secondary)]">Admin API Engine</span>
				<Badge variant="neutral" class="font-mono text-[10.5px]">Internal Bridge</Badge>
			</div>
			<div class="mt-1 font-mono text-xs font-medium text-[var(--text-primary)]">
				{caddyAdminUrl || 'http://localhost:2019'}
			</div>
			<span class="text-xs text-[var(--text-tertiary)]">
				Isolated inside private bridge network <span
					class="font-mono text-[11px] text-[var(--text-secondary)]">gopod-net</span
				>
			</span>
		</LayerCard>

		<!-- TLS & Security Policy -->
		<LayerCard class="flex flex-col gap-2 p-4">
			<div class="flex items-center justify-between">
				<span class="text-xs font-medium text-[var(--text-secondary)]">TLS Automation</span>
				<Badge variant="success" class="gap-1 text-xs">
					<Lock size={12} /> ACME v2
				</Badge>
			</div>
			<div class="mt-1 flex items-baseline gap-2">
				<span class="text-sm font-semibold text-[var(--text-primary)]">
					Let's Encrypt + Internal
				</span>
			</div>
			<span class="text-xs text-[var(--text-tertiary)]">
				Dual HTTP/HTTPS local development + automatic ACME on public FQDNs
			</span>
		</LayerCard>
	</div>

	<!-- Active Caddyfile Viewer Card -->
	<LayerCard class="overflow-hidden p-0 shadow-xs">
		<div
			class="flex flex-col justify-between gap-3 border-b border-[var(--border)] bg-[var(--bg-surface)] px-4 py-3 sm:flex-row sm:items-center"
		>
			<div class="flex flex-col gap-0.5">
				<div class="flex items-center gap-2">
					<span class="text-sm font-semibold text-[var(--text-primary)]">Active Caddyfile</span>
					<Badge variant="neutral" class="font-mono text-[11px]">Auto-reconciled</Badge>
				</div>
				<span class="text-xs text-[var(--text-tertiary)]">
					Declaratively generated by GOPOD Ingress Reconciler and synchronized via Caddy Admin API.
				</span>
			</div>

			<div class="flex items-center gap-2 self-start sm:self-auto">
				<Button
					variant="secondary"
					size="sm"
					onclick={handleCopyCaddyfile}
					disabled={!caddyfileContent}
					class="gap-1.5"
				>
					{#if copiedCaddyfile}
						<Check size={13} class="text-[var(--status-green)]" /> Copied
					{:else}
						<Copy size={13} /> Copy Caddyfile
					{/if}
				</Button>

				<Button
					variant="primary"
					size="sm"
					onclick={onReloadCaddy}
					disabled={isReloadingCaddy}
					class="gap-1.5"
				>
					<ArrowsClockwise size={13} class={isReloadingCaddy ? 'animate-spin' : ''} />
					{isReloadingCaddy ? 'Reloading...' : 'Reload Ingress'}
				</Button>
			</div>
		</div>

		<!-- Code Block / Editor -->
		<div class="w-full bg-[var(--bg-panel)] p-2">
			{#if isLoadingCaddyfile}
				<div class="flex h-80 items-center justify-center text-xs text-[var(--text-tertiary)]">
					<ArrowsClockwise size={18} class="mr-2 animate-spin text-[var(--accent)]" /> Loading current
					Caddyfile...
				</div>
			{:else if !caddyfileContent}
				<div
					class="flex h-80 flex-col items-center justify-center gap-2 text-center text-xs text-[var(--text-tertiary)]"
				>
					<span>No active Caddyfile loaded or Caddy ingress container offline.</span>
					<Button variant="secondary" size="xs" onclick={onRetryLoadCaddyfile}>Retry</Button>
				</div>
			{:else}
				<CodeEditor
					value={caddyfileContent}
					language="caddyfile"
					title="Caddyfile"
					readOnly={true}
					height="auto"
					lineNumbers={true}
				/>
			{/if}
		</div>

		<!-- Footer -->
		<div
			class="flex items-center justify-between border-t border-[var(--border)] bg-[var(--bg-table-header)] px-4 py-2 text-xs text-[var(--text-tertiary)]"
		>
			<span class="text-[11px]">Caddy reverse proxy and automatic HTTPS configuration</span>
			<span class="font-mono text-[11px]">/etc/caddy/Caddyfile</span>
		</div>
	</LayerCard>
</div>
